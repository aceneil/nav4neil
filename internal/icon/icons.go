const (
	directoryIcon  = ""
	executableIcon = ""
	linkIcon       = ""
	fileIcon       = ""
)

// IconFor returns the Nerd Font glyph for a directory, link, or regular file.
// name is case-insensitive, matching Yazi's IconNames behavior.
func IconFor(name string, isDir, isLink bool) string {
	lower := strings.ToLower(name)
	if isLink {
		return linkIcon
	}
	if isDir {
		if icon, ok := directoryIcons[lower]; ok {
			return icon
		}
		return directoryIcon
	}
	if icon, ok := fileNameIcons[lower]; ok {
		return icon
	}
	ext := strings.ToLower(pathpkg.Ext(name))
	ext = strings.TrimPrefix(ext, ".")
	if ext != "" {
		if icon, ok := fileExtensionIcons[ext]; ok {
			return icon
		}
	}
	return fileIcon
}

// Aligned returns an icon plus the fixed gap used before the item name.
func Aligned(name string, isDir, isLink bool) string {
	return IconFor(name, isDir, isLink) + " "
}
